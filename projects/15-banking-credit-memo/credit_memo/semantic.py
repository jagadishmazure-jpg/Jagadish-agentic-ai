MEASURES: dict[str, dict[str, Any]] = {
    "revenue": {"expr": "SUM(revenue)", "unit": "USD m", "grains": ["year"]},
    "ebitda": {"expr": "SUM(ebitda)", "unit": "USD m", "grains": ["year"]},
    "total_debt": {"expr": "LAST(total_debt)", "unit": "USD m", "grains": ["year"]},
    "debt_service": {"expr": "SUM(interest + principal)", "unit": "USD m", "grains": ["year"]},
    "dscr": {"expr": "ebitda / debt_service", "unit": "x", "grains": ["year"]},
    "leverage": {"expr": "total_debt / ebitda", "unit": "x", "grains": ["year"]},
}
FILTER_KEYS = {"borrower_id", "year"}
SQLISH = re.compile(r"select|drop|;|--|\bor\b\s+1=1|union", re.I)
VERSION = "credit-semantic-model v3"


class SemanticError(ValueError):
    pass


def _check(name: str, grain: str, filters: dict[str, Any]) -> None:
    if name not in MEASURES:
        raise SemanticError(f"unknown measure {name!r}; allowed: {sorted(MEASURES)}")
    if grain not in MEASURES[name]["grains"]:
        raise SemanticError(f"grain {grain!r} not available for {name}")
    unknown = set(filters) - FILTER_KEYS
    if unknown:
        raise SemanticError(f"unknown filter keys {sorted(unknown)}")
    if "borrower_id" not in filters:
        raise SemanticError("borrower_id filter is mandatory (row-level scope)")
    if any(SQLISH.search(str(v)) for v in filters.values()):
        raise SemanticError("filter values must be literals (no SQL)")


def _value(row: dict[str, Any], name: str) -> float:
    ds = row["interest"] + row["principal"]
    derived = {
        "debt_service": ds,
        "dscr": row["ebitda"] / ds,
        "leverage": row["total_debt"] / row["ebitda"],
    }
    return round(derived.get(name, row.get(name, 0.0)), 2)


def get_measure(
    name: str, grain: str, filters: dict[str, Any], dry_run: bool = True
) -> dict[str, Any]:
    _check(name, grain, filters)
    years = filters.get("year")
    years = set(years) if isinstance(years, list) else {years} if years else None
    rows = [
        r
        for r in GOLD
        if r["borrower_id"] == filters["borrower_id"] and (years is None or r["year"] in years)
    ]
    if dry_run:
        return {
            "plan": {
                "semantic_model": "credit_gold.borrower_financials",
                "measure": name,
                "expression": MEASURES[name]["expr"],
                "grain": grain,
                "filters": filters,
                "estimated_rows": len(rows),
                "sql": "generated by the semantic layer at execution",
            },
            "version": VERSION,
        }
    return {
        "measure": name,
        "unit": MEASURES[name]["unit"],
        "version": VERSION,
        "values": [{"year": r["year"], "value": _value(r, name)} for r in rows],
    }
