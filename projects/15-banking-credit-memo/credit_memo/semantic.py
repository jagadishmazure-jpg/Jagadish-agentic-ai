"""Semantic layer over the gold credit mart: governed measures only, no raw SQL.

``get_measure(name, grain, filters, dry_run)``:
* ``name`` must be a registered measure, ``grain`` one of its grains, ``filters`` only known
  keys; ``borrower_id`` is mandatory (row-level scope). Anything else is rejected.
* ``dry_run=True`` returns the compiled plan (model, expression, filters, row estimate) so the
  caller can check it before executing. The SQL is generated by the layer, never the agent.
"""

